# Exercício 16 - Positivo, negativo ou zero.

numero = float(input("Digite um número: "))

if numero > 0:
    print("RESULTADO: POSITIVO")

elif numero < 0:
    print("RESULTADO: NEGATIVO")

else:
    print("RESULTADO: ZERO")

