print("Digite um número entre 1 a 7 e veja o dia da semana")
numero = int(input("correspondente à esse número: "))
print("")

if numero == 1:
    print("SEGUNDA-FEIRA.")

elif numero == 2:
    print("TERÇA-FEIRA.")

elif numero == 3:
    print("QUARTA-FEIRA.")

elif numero == 4:
    print("QUINTA-FEIRA.")

elif numero == 5:
    print("SEXTA-FEIRA")

elif numero == 6:
    print("SÁBADO.")

elif numero == 7:
    print("DOMINGO.")

else:
    print("OPÇÃO INVÁLIDA.")