#  Exercício 3 -  Antecessor e sucessor.

numero = float(input("Digite um número: "))

antecessor = numero - 1
sucessor = numero + 1

print(f"Antecessor: {antecessor}")
print(f"Número: {numero}")
print(f"Sucessor: {sucessor}")

